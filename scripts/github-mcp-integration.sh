# Sync Beads tasks to GitHub Issues
sync_beads_to_github() {
  echo -e "${BLUE}🔄 Syncing Beads tasks to GitHub Issues${NC}"

  if ! command -v bd &> /dev/null; then
    echo -e "${RED}❌ Beads not installed${NC}"
    exit 1
  fi

  # Get all open Beads tasks
  local beads_tasks=$(bd list --status open --json)

  if [ "$(echo "$beads_tasks" | jq 'length')" -eq 0 ]; then
    echo -e "${YELLOW}No open Beads tasks to sync${NC}"
    return
  fi

  echo "Found $(echo "$beads_tasks" | jq 'length') open Beads tasks"
  echo ""

  echo "$beads_tasks" | jq -c '.[]' | while IFS= read -r task; do
    sync_single_task_to_github "$task"
  done
}

# Sync a single Beads task to GitHub
sync_single_task_to_github() {
  local task_json="$1"

  local task_id=$(echo "$task_json" | jq -r '.id')
  local task_title=$(echo "$task_json" | jq -r '.title')
  local task_desc=$(echo "$task_json" | jq -r '.description // ""')
  local task_priority=$(echo "$task_json" | jq -r '.priority // "normal"')
  local task_assignee=$(echo "$task_json" | jq -r '.assignee // ""')

  # Check if already synced (has github_issue metadata)
  local github_issue=$(echo "$task_json" | jq -r '.metadata.github_issue // ""')

  if [ -n "$github_issue" ]; then
    echo -e "${YELLOW}⏭️  ${task_id} already synced to issue #${github_issue}${NC}"
    return
  fi

  echo -e "${BLUE}Creating issue for ${task_id}: ${task_title}${NC}"

  # Map priority to GitHub labels
  local labels="ai-pack,beads-synced"
  case "$task_priority" in
    critical) labels="${labels},priority-critical" ;;
    high) labels="${labels},priority-high" ;;
    normal) labels="${labels},priority-normal" ;;
    low) labels="${labels},priority-low" ;;
  esac

  # Create issue body
  local issue_body="**Beads Task:** ${task_id}
**Priority:** ${task_priority}

${task_desc}

---
🔗 Synced from Beads task ${task_id}
🤖 Managed by ai-pack"

  # Create GitHub issue
  local issue=$(github_api_call "/repos/${GITHUB_REPO}/issues" POST "$(jq -n \
    --arg title "$task_title" \
    --arg body "$issue_body" \
    --arg labels "$labels" \
    '{
      title: $title,
      body: $body,
      labels: ($labels | split(","))
    }')")

  local issue_number=$(echo "$issue" | jq -r '.number')

  if [ -z "$issue_number" ] || [ "$issue_number" = "null" ]; then
    echo -e "${RED}❌ Failed to create issue${NC}"
    return
  fi

  echo -e "${GREEN}✅ Created issue #${issue_number}${NC}"

  # Update Beads task with GitHub issue reference
  bd comment "$task_id" "GitHub Issue: #${issue_number}"

  # Store metadata (requires Beads metadata support)
  # bd metadata set "$task_id" github_issue "$issue_number"
}

# Create Epic from Beads task and subtasks
create_epic_from_beads() {
  local epic_task_id="$1"

  if [ -z "$epic_task_id" ]; then
    echo "Usage: create_epic_from_beads <beads-task-id>"
    exit 1
  fi

  echo -e "${BLUE}📚 Creating Epic from Beads task ${epic_task_id}${NC}"

  # Get epic task details
  local epic_task=$(bd show "$epic_task_id" --json)
  local epic_title=$(echo "$epic_task" | jq -r '.title')
  local epic_desc=$(echo "$epic_task" | jq -r '.description // ""')

  # Find dependent tasks (subtasks)
  local subtasks=$(bd list --json | jq -r --arg epic "$epic_task_id" \
    '.[] | select(.dependencies[]? == $epic) | @json')

  local subtask_count=$(echo "$subtasks" | wc -l)

  echo "Epic: ${epic_title}"
  echo "Subtasks: ${subtask_count}"
  echo ""

  # Create Epic issue
  local epic_body="# Epic: ${epic_title}

${epic_desc}

## Subtasks
"

  # Add subtask placeholders
  echo "$subtasks" | while IFS= read -r subtask; do
    local subtask_title=$(echo "$subtask" | jq -r '.title')
    epic_body="${epic_body}
- [ ] ${subtask_title}"
  done

  epic_body="${epic_body}

---
🔗 Epic from Beads task ${epic_task_id}
🤖 Managed by ai-pack"

  # Create Epic issue
  local epic_issue=$(github_api_call "/repos/${GITHUB_REPO}/issues" POST "$(jq -n \
    --arg title "Epic: $epic_title" \
    --arg body "$epic_body" \
    '{
      title: $title,
      body: $body,
      labels: ["epic", "ai-pack"]
    }')")

  local epic_number=$(echo "$epic_issue" | jq -r '.number')
  echo -e "${GREEN}✅ Created Epic issue #${epic_number}${NC}"

  # Create subtask issues
  echo ""
  echo -e "${BLUE}Creating subtask issues...${NC}"

  echo "$subtasks" | while IFS= read -r subtask; do
    local subtask_id=$(echo "$subtask" | jq -r '.id')
    local subtask_title=$(echo "$subtask" | jq -r '.title')
    local subtask_desc=$(echo "$subtask" | jq -r '.description // ""')

    local subtask_body="**Beads Task:** ${subtask_id}
**Epic:** #${epic_number}

${subtask_desc}

---
🔗 Part of Epic #${epic_number}
🤖 Managed by ai-pack"

    local subtask_issue=$(github_api_call "/repos/${GITHUB_REPO}/issues" POST "$(jq -n \
      --arg title "$subtask_title" \
      --arg body "$subtask_body" \
      '{
        title: $title,
        body: $body,
        labels: ["story", "ai-pack"]
      }')")

    local subtask_number=$(echo "$subtask_issue" | jq -r '.number')
    echo "  ✅ Created story #${subtask_number}: ${subtask_title}"

    # Link in Beads
    bd comment "$subtask_id" "GitHub Issue: #${subtask_number} (Epic: #${epic_number})"
  done

  echo ""
  echo -e "${GREEN}✅ Epic creation complete${NC}"
  echo "   View: https://github.com/${GITHUB_REPO}/issues/${epic_number}"
}

