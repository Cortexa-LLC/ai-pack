# Monitor CI/CD workflows and detect failures
monitor_workflows() {
  echo -e "${BLUE}📊 Monitoring CI/CD Workflows${NC}"

  local branch="${1:-$(git rev-parse --abbrev-ref HEAD)}"
  local commit="${2:-$(git rev-parse HEAD)}"

  echo "Branch: ${branch}"
  echo "Commit: ${commit:0:7}"
  echo ""

  # Get workflow runs for this commit
  local runs=$(github_api_call "/repos/${GITHUB_REPO}/actions/runs?head_sha=${commit}" GET)

  if [ "$(echo "$runs" | jq '.total_count')" -eq 0 ]; then
    echo -e "${YELLOW}⏳ No workflow runs found for this commit yet${NC}"
    return
  fi

  echo -e "${GREEN}Workflow Runs:${NC}"
  echo "$runs" | jq -r '.workflow_runs[] | "\(.name): \(.status) - \(.conclusion // "running")"'

  # Check for failures
  local failures=$(echo "$runs" | jq -r '.workflow_runs[] | select(.conclusion == "failure") | @json')

  if [ -n "$failures" ]; then
    echo ""
    echo -e "${RED}❌ Failed Workflows Detected${NC}"
    echo "$failures" | while IFS= read -r workflow; do
      handle_workflow_failure "$workflow"
    done
  else
    echo ""
    echo -e "${GREEN}✅ All workflows passing${NC}"
  fi
}

# Handle a workflow failure
handle_workflow_failure() {
  local workflow_json="$1"

  local workflow_name=$(echo "$workflow_json" | jq -r '.name')
  local workflow_id=$(echo "$workflow_json" | jq -r '.id')
  local workflow_url=$(echo "$workflow_json" | jq -r '.html_url')

  echo ""
  echo -e "${RED}Failure Details: ${workflow_name}${NC}"
  echo "  URL: ${workflow_url}"

  # Get job details
  local jobs=$(github_api_call "/repos/${GITHUB_REPO}/actions/runs/${workflow_id}/jobs" GET)
  local failed_jobs=$(echo "$jobs" | jq -r '.jobs[] | select(.conclusion == "failure")')

  echo "$failed_jobs" | jq -r '"  Failed Job: \(.name)"'

  # Extract failure logs
  echo ""
  echo -e "${YELLOW}Analyzing failures...${NC}"

  local failure_summary=$(echo "$failed_jobs" | jq -r '.steps[] | select(.conclusion == "failure") | "  - \(.name): \(.conclusion)"')
  echo "$failure_summary"

  # Create GitHub issue for failure
  create_failure_issue "$workflow_name" "$workflow_url" "$failure_summary"

  # Create Beads task for fixing
  create_failure_beads_task "$workflow_name" "$workflow_url"
}

# Create GitHub issue for CI failure
create_failure_issue() {
  local workflow_name="$1"
  local workflow_url="$2"
  local failure_summary="$3"

  local issue_title="CI Failure: ${workflow_name}"
  local issue_body="## CI/CD Failure Detected

**Workflow:** ${workflow_name}
**URL:** ${workflow_url}
**Date:** $(date -u +%Y-%m-%dT%H:%M:%SZ)

### Failed Steps
${failure_summary}

### Action Required
Investigate and fix the failing workflow.

### Related
- Automated detection by AI-Pack
- Check logs for detailed error messages

---
🤖 Auto-generated by ai-pack/scripts/github-mcp-integration.sh"

  echo ""
  echo -e "${BLUE}Creating GitHub issue...${NC}"

  local issue=$(github_api_call "/repos/${GITHUB_REPO}/issues" POST "$(jq -n \
    --arg title "$issue_title" \
    --arg body "$issue_body" \
    '{
      title: $title,
      body: $body,
      labels: ["ci-failure", "automated", "priority-high"]
    }')")

  local issue_number=$(echo "$issue" | jq -r '.number')
  echo -e "${GREEN}✅ Created issue #${issue_number}${NC}"
  echo "   ${workflow_url}"
}

# Create Beads task for CI failure
create_failure_beads_task() {
  local workflow_name="$1"
  local workflow_url="$2"

  if ! command -v bd &> /dev/null; then
    echo -e "${YELLOW}⚠️  Beads not installed, skipping task creation${NC}"
    return
  fi

  local task_id=$(bd create "Fix CI failure: ${workflow_name}" \
    --priority critical \
    --description "CI workflow failing. See: ${workflow_url}" \
    --json | jq -r '.id')

  echo -e "${GREEN}✅ Created Beads task: ${task_id}${NC}"

  # Commit Beads changes
  git add .beads/issues.jsonl
  git commit -m "Add Beads task for CI failure: ${workflow_name}" || true
}

