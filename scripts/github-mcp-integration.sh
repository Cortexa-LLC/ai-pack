#!/bin/bash
# GitHub MCP Integration Script for AI-Pack
# Version: 1.0.0
# Date: 2026-01-18
#
# This script provides GitHub MCP integration capabilities:
# - CI/CD workflow monitoring and failure handling
# - Issue/Epic/Story creation from Beads tasks
# - PR management and quality gate checks
# - Beads ↔ GitHub synchronization
#
# Prerequisites:
# - GitHub MCP server running (docker or native)
# - GITHUB_TOKEN environment variable set
# - jq installed for JSON parsing
# - Beads (bd) installed

set -e

# Configuration
GITHUB_MCP_URL="${GITHUB_MCP_URL:-http://localhost:3000}"
GITHUB_REPO="${GITHUB_REPO:-$(git config --get remote.origin.url | sed 's/.*github.com[:/]\(.*\)\.git/\1/')}"
GITHUB_TOKEN="${GITHUB_TOKEN}"

if [ -z "$GITHUB_TOKEN" ]; then
  echo "❌ Error: GITHUB_TOKEN not set"
  exit 1
fi

# Color output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Helper: Call GitHub MCP API
github_mcp_call() {
  local endpoint="$1"
  local method="${2:-GET}"
  local data="${3:-}"

  local curl_cmd="curl -s -X ${method} \
    -H 'Authorization: Bearer ${GITHUB_TOKEN}' \
    -H 'Content-Type: application/json' \
    ${GITHUB_MCP_URL}${endpoint}"

  if [ -n "$data" ]; then
    curl_cmd="${curl_cmd} -d '${data}'"
  fi

  eval $curl_cmd
}

# Helper: Call GitHub API directly (for features not in MCP yet)
github_api_call() {
  local endpoint="$1"
  local method="${2:-GET}"
  local data="${3:-}"

  local curl_cmd="curl -s -X ${method} \
    -H 'Authorization: token ${GITHUB_TOKEN}' \
    -H 'Accept: application/vnd.github.v3+json' \
    https://api.github.com${endpoint}"

  if [ -n "$data" ]; then
    curl_cmd="${curl_cmd} -d '${data}'"
  fi

  eval $curl_cmd
}

