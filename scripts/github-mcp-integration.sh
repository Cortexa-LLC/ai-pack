# Main CLI router
main() {
  if [ $# -eq 0 ]; then
    show_help
    exit 0
  fi

  local command="$1"
  shift

  case "$command" in
    monitor)
      monitor_workflows "$@"
      ;;
    sync-beads)
      sync_beads_to_github
      ;;
    create-epic)
      create_epic_from_beads "$@"
      ;;
    check-pr)
      check_pr_quality_gates "$@"
      ;;
    create-pr)
      create_pr_from_branch "$@"
      ;;
    watch)
      watch_and_recover
      ;;
    help|--help|-h)
      show_help
      ;;
    *)
      echo -e "${RED}❌ Unknown command: $command${NC}"
      echo ""
      show_help
      exit 1
      ;;
  esac
}

# Run main if executed directly
if [ "${BASH_SOURCE[0]}" = "${0}" ]; then
  main "$@"
fi
