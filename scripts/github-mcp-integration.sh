# Watch for failures and auto-create remediation tasks
watch_and_recover() {
  echo -e "${BLUE}👀 Watching for CI failures (Ctrl+C to stop)${NC}"
  echo ""

  local last_check=$(date +%s)

  while true; do
    local current_time=$(date +%s)

    # Check every 60 seconds
    if [ $((current_time - last_check)) -ge 60 ]; then
      echo "[$(date +%H:%M:%S)] Checking workflows..."

      local recent_runs=$(github_api_call "/repos/${GITHUB_REPO}/actions/runs?per_page=5" GET)
      local failures=$(echo "$recent_runs" | jq -r '.workflow_runs[] | select(.conclusion == "failure" and .created_at > (now - 3600 | todate)) | @json')

      if [ -n "$failures" ]; then
        echo "$failures" | while IFS= read -r workflow; do
          local workflow_id=$(echo "$workflow" | jq -r '.id')

          # Check if we already handled this failure
          if [ -f "/tmp/ai-pack-handled-${workflow_id}" ]; then
            continue
          fi

          echo -e "${RED}🚨 New failure detected${NC}"
          handle_workflow_failure "$workflow"

          # Mark as handled
          touch "/tmp/ai-pack-handled-${workflow_id}"
        done
      fi

      last_check=$current_time
    fi

    sleep 10
  done
}

