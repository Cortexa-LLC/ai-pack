# Check PR status and quality gates
check_pr_quality_gates() {
  local pr_number="$1"

  if [ -z "$pr_number" ]; then
    echo "Usage: check_pr_quality_gates <pr-number>"
    exit 1
  fi

  echo -e "${BLUE}🔍 Checking PR #${pr_number} Quality Gates${NC}"
  echo ""

  # Get PR details
  local pr=$(github_api_call "/repos/${GITHUB_REPO}/pulls/${pr_number}" GET)
  local pr_title=$(echo "$pr" | jq -r '.title')
  local pr_head=$(echo "$pr" | jq -r '.head.sha')
  local pr_base=$(echo "$pr" | jq -r '.base.ref')

  echo "PR: ${pr_title}"
  echo "Head: ${pr_head:0:7}"
  echo "Base: ${pr_base}"
  echo ""

  # Check CI status
  echo -e "${BLUE}1. CI/CD Status${NC}"
  local status=$(github_api_call "/repos/${GITHUB_REPO}/commits/${pr_head}/status" GET)
  local state=$(echo "$status" | jq -r '.state')

  case "$state" in
    success)
      echo -e "   ${GREEN}✅ All checks passing${NC}"
      ;;
    pending)
      echo -e "   ${YELLOW}⏳ Checks in progress${NC}"
      ;;
    failure)
      echo -e "   ${RED}❌ Checks failing${NC}"
      local failing=$(echo "$status" | jq -r '.statuses[] | select(.state == "failure") | .context')
      echo "$failing" | while read -r check; do
        echo "      - ${check}"
      done
      ;;
  esac

  # Check for TDD compliance (if ci/tdd-validation exists)
  echo ""
  echo -e "${BLUE}2. TDD Compliance${NC}"
  local tdd_check=$(echo "$status" | jq -r '.statuses[] | select(.context == "ci/tdd-validation") | .state')
  if [ -n "$tdd_check" ]; then
    if [ "$tdd_check" = "success" ]; then
      echo -e "   ${GREEN}✅ TDD validated${NC}"
    else
      echo -e "   ${RED}❌ TDD validation failed${NC}"
    fi
  else
    echo -e "   ${YELLOW}⚠️  TDD validation not configured${NC}"
  fi

  # Check test coverage (if ci/coverage exists)
  echo ""
  echo -e "${BLUE}3. Test Coverage${NC}"
  local coverage_check=$(echo "$status" | jq -r '.statuses[] | select(.context == "ci/coverage") | .state')
  if [ -n "$coverage_check" ]; then
    if [ "$coverage_check" = "success" ]; then
      echo -e "   ${GREEN}✅ Coverage meets threshold${NC}"
    else
      echo -e "   ${RED}❌ Coverage below threshold${NC}"
    fi
  else
    echo -e "   ${YELLOW}⚠️  Coverage check not configured${NC}"
  fi

  # Check for reviews
  echo ""
  echo -e "${BLUE}4. Code Reviews${NC}"
  local reviews=$(github_api_call "/repos/${GITHUB_REPO}/pulls/${pr_number}/reviews" GET)
  local approved=$(echo "$reviews" | jq -r '[.[] | select(.state == "APPROVED")] | length')
  local changes_requested=$(echo "$reviews" | jq -r '[.[] | select(.state == "CHANGES_REQUESTED")] | length')

  echo "   Approved: ${approved}"
  echo "   Changes Requested: ${changes_requested}"

  if [ "$changes_requested" -gt 0 ]; then
    echo -e "   ${RED}❌ Changes requested${NC}"
  elif [ "$approved" -ge 1 ]; then
    echo -e "   ${GREEN}✅ Approved${NC}"
  else
    echo -e "   ${YELLOW}⏳ Awaiting review${NC}"
  fi

  # Overall gate status
  echo ""
  echo -e "${BLUE}Overall Status:${NC}"

  if [ "$state" = "success" ] && [ "$approved" -ge 1 ] && [ "$changes_requested" -eq 0 ]; then
    echo -e "${GREEN}✅ All quality gates passed - ready to merge${NC}"
    return 0
  else
    echo -e "${RED}❌ Quality gates not met${NC}"
    return 1
  fi
}

# Create PR from current branch
create_pr_from_branch() {
  local branch=$(git rev-parse --abbrev-ref HEAD)
  local base="${1:-main}"

  if [ "$branch" = "$base" ]; then
    echo -e "${RED}❌ Cannot create PR from ${base} to ${base}${NC}"
    exit 1
  fi

  echo -e "${BLUE}🔀 Creating PR from ${branch} to ${base}${NC}"

  # Find related Beads task
  local beads_task=""
  if command -v bd &> /dev/null; then
    beads_task=$(bd list --status in_progress --json | jq -r '.[0].id // ""')
  fi

  # Generate PR title and body
  local pr_title="Implement feature from ${branch}"
  local pr_body="## Changes

[Describe changes here]

"

  if [ -n "$beads_task" ]; then
    pr_body="${pr_body}**Beads Task:** ${beads_task}
"
  fi

  pr_body="${pr_body}
## Testing
- [ ] Tests passing
- [ ] Coverage adequate
- [ ] Manual testing complete

## Checklist
- [ ] TDD followed
- [ ] Code reviewed
- [ ] Documentation updated

---
🤖 Created by ai-pack/scripts/github-mcp-integration.sh"

  # Push branch
  echo "Pushing branch..."
  git push -u origin "$branch"

  # Create PR
  local pr=$(github_api_call "/repos/${GITHUB_REPO}/pulls" POST "$(jq -n \
    --arg title "$pr_title" \
    --arg body "$pr_body" \
    --arg head "$branch" \
    --arg base "$base" \
    '{
      title: $title,
      body: $body,
      head: $head,
      base: $base
    }')")

  local pr_number=$(echo "$pr" | jq -r '.number')
  local pr_url=$(echo "$pr" | jq -r '.html_url')

  if [ -z "$pr_number" ] || [ "$pr_number" = "null" ]; then
    echo -e "${RED}❌ Failed to create PR${NC}"
    echo "$pr" | jq '.'
    exit 1
  fi

  echo -e "${GREEN}✅ Created PR #${pr_number}${NC}"
  echo "   ${pr_url}"

  # Link in Beads if task exists
  if [ -n "$beads_task" ]; then
    bd comment "$beads_task" "GitHub PR: #${pr_number} - ${pr_url}"
    echo -e "${GREEN}✅ Linked to Beads task ${beads_task}${NC}"
  fi
}

